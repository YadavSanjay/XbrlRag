"""C1: full written dates and their exact spans (docs/specs/fiscal-year-ended-date.md, req. 1).

Oracle: the written text, read by hand; ``datetime.date`` decides whether a generated day and
month form a real date.
"""

from __future__ import annotations

from datetime import date, timedelta

import pytest
from hypothesis import given
from hypothesis import strategies as st

from src.retriever.xbrl.fiscal_date import find_written_dates


def _found(text):
    got = find_written_dates(text)
    assert isinstance(got, list), got
    return [(d, text[s:e]) for d, s, e in got]


@pytest.mark.criterion("C1")
@pytest.mark.parametrize(
    ("text", "expected"),
    [
        ("February 2, 2025", [(date(2025, 2, 2), "February 2, 2025")]),
        ("february 2 2025", [(date(2025, 2, 2), "february 2 2025")]),
        ("Feb. 2, 2025", [(date(2025, 2, 2), "Feb. 2, 2025")]),
        ("Feb 2, 2025", [(date(2025, 2, 2), "Feb 2, 2025")]),
        ("Sept. 28, 2024", [(date(2024, 9, 28), "Sept. 28, 2024")]),
        ("Sep 28 2024", [(date(2024, 9, 28), "Sep 28 2024")]),
        ("May 4, 2025", [(date(2025, 5, 4), "May 4, 2025")]),
        ("February 2nd, 2025", [(date(2025, 2, 2), "February 2nd, 2025")]),
        ("DECEMBER 31, 2024", [(date(2024, 12, 31), "DECEMBER 31, 2024")]),
        ("2 February 2025", [(date(2025, 2, 2), "2 February 2025")]),
        ("1st Feb. 2026", [(date(2026, 2, 1), "1st Feb. 2026")]),
        ("28 January, 2024", [(date(2024, 1, 28), "28 January, 2024")]),
        ("2025-02-02", [(date(2025, 2, 2), "2025-02-02")]),
    ],
)
def test_each_form_alone(text, expected):
    # oracle: requirement 1's forms F1, F2, F3, read by hand
    assert _found(text) == expected


@pytest.mark.criterion("C1")
def test_dates_inside_a_sentence_in_order():
    # oracle: by hand — the fourth C9 dev mention and a mixed-form sentence; the sentence's own
    # full stop is not part of the date
    q = ("In the annual report for the fiscal year ended February 1, 2026, what did HD show as "
         "its EPS for the fiscal year ended January 28, 2024?")
    assert _found(q) == [(date(2026, 2, 1), "February 1, 2026"),
                         (date(2024, 1, 28), "January 28, 2024")]
    s = "Between 2024-01-28 and 1 February 2026, versus the year ended Feb. 2, 2025."
    assert _found(s) == [(date(2024, 1, 28), "2024-01-28"), (date(2026, 2, 1), "1 February 2026"),
                         (date(2025, 2, 2), "Feb. 2, 2025")]


@pytest.mark.criterion("C1")
def test_non_forms_are_not_dates():
    # oracle: requirement 1's list of non-forms, by hand; the last text adds one real date so
    # an empty answer for everything is not enough
    for text in ("February 30, 2025", "2025-13-01", "2025-02-30", "02/02/2025", "2/2/25",
                 "Feb 2, '25", "January 2025", "the end of January 2025", "fiscal 2025",
                 "FY25", "x2025-02-02", "February 2, 20251", "Mayday 4, 2025"):
        assert _found(text) == [], text
    assert _found("02/02/2025 or February 2, 2025") == [(date(2025, 2, 2), "February 2, 2025")]


_MONTHS = ["January", "February", "March", "April", "May", "June", "July", "August",
           "September", "October", "November", "December"]
_ABBR = ["Jan", "Feb", "Mar", "Apr", None, "Jun", "Jul", "Aug", "Sep", "Oct", "Nov", "Dec"]
_ORD = {1: "st", 2: "nd", 3: "rd", 21: "st", 22: "nd", 23: "rd", 31: "st"}


def _write(d: date, form: int, abbr: bool, dot: bool, comma: bool, ordinal: bool) -> str:
    month = _MONTHS[d.month - 1]
    if abbr and _ABBR[d.month - 1]:
        month = _ABBR[d.month - 1] + ("." if dot else "")
    day = f"{d.day}{_ORD.get(d.day, 'th') if ordinal else ''}"
    if form == 1:
        return f"{month} {day}{',' if comma else ''} {d.year}"
    if form == 2:
        return f"{day} {month}{',' if comma else ''} {d.year}"
    return d.isoformat()


@pytest.mark.criterion("C1")
@given(
    d=st.dates(min_value=date(1900, 1, 1), max_value=date(2099, 12, 31)),
    form=st.sampled_from([1, 2, 3]),
    abbr=st.booleans(), dot=st.booleans(), comma=st.booleans(), ordinal=st.booleans(),
    before=st.lists(st.sampled_from(["the", "fiscal", "year", "ended", "as", "of", "(", "on"]),
                    max_size=4),
    after=st.lists(st.sampled_from(["for", "HD", "revenue", ".", "?", ")", "and"]), max_size=4),
)
def test_any_real_date_in_any_form_is_found_with_its_span(d, form, abbr, dot, comma, ordinal,
                                                          before, after):
    # oracle: the date is generated by datetime.date and written by hand-coded rules of
    # requirement 1; its span is where it was written
    written = _write(d, form, abbr, dot, comma, ordinal)
    head = " ".join(before) + (" " if before else "")
    text = head + written + (" " if after else "") + " ".join(after)
    assert find_written_dates(text) == [(d, len(head), len(head) + len(written))]


@pytest.mark.criterion("C1")
@given(d=st.dates(min_value=date(1900, 1, 1), max_value=date(2099, 12, 1)),
       form=st.sampled_from([1, 2]))
def test_a_day_past_the_month_end_is_no_date(d, form):
    # oracle: datetime.date — day (last day of the month + 1) does not exist; one real date is
    # appended so the result must still find that one
    last = (d.replace(day=28) + timedelta(days=4)).replace(day=1) - timedelta(days=1)
    month = _MONTHS[d.month - 1]
    bad = (f"{month} {last.day + 1}, {d.year}" if form == 1 else
           f"{last.day + 1} {month} {d.year}")
    text = f"{bad} and {_write(d, 1, False, False, True, False)}"
    got = [v for v, _s, _e in find_written_dates(text)]
    assert got == [d]
